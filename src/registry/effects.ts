/** Library defaults that differ from the playground's starting values. */
const libDefaults: Record<string, Record<string, string>> = {
  "mask-wipe": { barColor: "currentColor" },
  "scramble-decode": { scrambleColor: "" },
  typewriter: { cursorColor: "" },
  "hover-shuffle": { activeColor: "" },
  "kinetic-underline": { color: "currentColor" },
  "sticky-typography": { invertColor: "" },
  "editorial-split": { kicker: "" },
};
for (const e of effects) {
  const d = libDefaults[e.slug];
  if (!d) continue;
  e.controls = e.controls.map((c) => (c.key in d && (c.type === "color" || c.type === "text") ? { ...c, libDefault: d[c.key] } : c));
}

export const effectBySlug = Object.fromEntries(effects.map((e) => [e.slug, e])) as Record<string, EffectMeta>;

/** The control defaults for an effect, as a props object. */
export function defaultProps(meta: EffectMeta) {
  return Object.fromEntries(meta.controls.map((c) => [c.key, c.default]));
}
