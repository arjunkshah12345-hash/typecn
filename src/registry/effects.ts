import type { Control, EffectMeta } from "./types";

/* ------------------------------- control kit ------------------------------- */

export const EASINGS = ["expo.out", "power.out", "expo.inOut", "quart.inOut", "circ.out", "back.out", "sine.inOut", "spring", "spring.soft", "linear"] as const;

const range = (key: string, label: string, def: number, min: number, max: number, step: number, unit?: string, hint?: string): Control => ({
  type: "range",
  key,
  label,
  default: def,
  min,
  max,
  step,
  unit,
  hint,
  group: "effect",
});
const select = (key: string, label: string, def: string, options: readonly string[], hint?: string): Control => ({ type: "select", key, label, default: def, options, hint, group: "effect" });
const toggle = (key: string, label: string, def: boolean, hint?: string): Control => ({ type: "toggle", key, label, default: def, hint, group: "effect" });
const color = (key: string, label: string, def: string, hint?: string): Control => ({ type: "color", key, label, default: def, hint, group: "effect" });
const text = (key: string, label: string, def: string, hint?: string): Control => ({ type: "text", key, label, default: def, hint, group: "effect" });

/** Standard timing controls for one-shot (replayable) animations. */
function timed(
  d: { duration: number; stagger?: number; easing?: string; delay?: number },
  opts: { stagger?: boolean; easing?: boolean; loopDefault?: boolean; loopLib?: boolean; durationMax?: number; staggerMax?: number } = {},
): Control[] {
  const out: Control[] = [
    { type: "range", key: "duration", label: "Duration", default: d.duration, min: 100, max: opts.durationMax ?? 4000, step: 50, unit: "ms", group: "timing" },
    { type: "range", key: "delay", label: "Delay", default: d.delay ?? 0, min: 0, max: 2000, step: 50, unit: "ms", group: "timing" },
  ];
  if (opts.stagger !== false)
    out.push({ type: "range", key: "stagger", label: "Stagger", default: d.stagger ?? 30, min: 0, max: opts.staggerMax ?? 300, step: 1, unit: "ms", group: "timing" });
  if (opts.easing !== false) out.push({ type: "select", key: "easing", label: "Easing", default: d.easing ?? "expo.out", options: EASINGS, group: "timing" });
  out.push(
    { type: "select", key: "trigger", label: "Trigger", default: "mount", options: ["mount", "inView", "hover"], group: "timing", hint: "What starts the animation in your app." },
    { type: "toggle", key: "loop", label: "Loop", default: opts.loopDefault ?? true, libDefault: opts.loopLib ?? false, group: "timing" },
  );
  return out;
}

const speed = (def = 1): Control => ({ type: "range", key: "speed", label: "Speed", default: def, min: 0.1, max: 3, step: 0.05, unit: "×", group: "timing" });

